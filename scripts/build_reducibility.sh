#!/usr/bin/env bash
# Generate and build the C-reducibility certificates of the 633 configurations.
#
#   scripts/build_reducibility.sh gen
#       (Re)generate FourColor/Reducibility/CfNNN.lean (NNN = 001 … 633), one per configuration,
#       each importing FourColor.Reducibility.Nets<r> (r = its ring size) and running
#       `#engine_certify cfNNN`, and FourColor/Reducibility.lean (`theReducibility`).
#       The ring sizes are computed by Lean (`cprsize cf.cfprog`); the output is deterministic.
#
#   scripts/build_reducibility.sh build [options]
#       Build the certificates in order (by configuration number) with at most J Lean processes
#       at a time, recording the wall time, CPU time, peak memory and .olean size of each one.
#       Steps: (1) `lake build` of FourColor.CfReducible and the needed Nets<r> modules;
#       (2) `lake build FourColor.Reducibility.CfNNN` for each selected configuration, J at a
#       time (the prerequisites being built, the concurrent `lake` processes only build their
#       own module); (3) if all 633 are selected, `lake build FourColor.Reducibility`.
#     options:
#       -j J            parallel Lean processes (default 3; each takes up to ~1.5 GB, ring 14)
#       --range A B     only the configurations A … B (numbers, inclusive; default 1 633)
#       --only "N …"    only the configurations with these numbers
#       --timeout S     per-module timeout in seconds (default 2400)
#       --log FILE      timing table (TSV; default .lake/reducibility/timings.tsv), appended to
#       --direct        compile with `scripts/lean.sh -o … -i …` instead of `lake build`
#                       (no lake traces: for measurements in a shared working tree, where the
#                       prerequisites' .olean files already exist; `lake build` will rebuild
#                       these modules later)
#       --no-collate    do not build FourColor.Reducibility at the end, even if all 633 are
#                       selected
#       --dry-run       print the commands instead of running them
#
# Timing lines have the columns: cf ring rc wall_s cpu_s maxrss_MB anon_MB olean_bytes
# (maxrss includes the memory-mapped Mathlib .olean files; anon is the private memory).
# The per-module build logs go next to the timing table (<log dir>/logs/CfNNN.log).
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1
ROOT=$(pwd)
export PATH=$HOME/.elan/bin:$PATH
NCONF=633
DIR=FourColor/Reducibility

# `memtime LABEL CMD…`: run CMD, print `MEMTIME LABEL wall=…s cpu=…s maxrss=…MB anon=…MB rc=…`
# (scripts/engine_memtime.py: maxrss/anon are the peaks of the summed resident/private memory of
# the command and all its descendants, sampled every 0.2 s; anon is 0 on macOS).  With
# MEMTIME_TIMEOUT=S the command is killed after S seconds (rc=TIMEOUT).
memtime() {
  local label=$1; shift
  python3 "$ROOT/scripts/engine_memtime.py" ${MEMTIME_TIMEOUT:+--timeout "$MEMTIME_TIMEOUT"} \
    --label "$label" -- "$@"
}

cfname() { printf 'cf%03d' "$1"; }
modname() { printf 'Cf%03d' "$1"; }

# ---------------------------------------------------------------------------- generation
gen() {
  local rings
  rings=$(printf '%s\n' \
    'import FourColor.Configurations' \
    'open FourColor in' \
    '#eval IO.println (" ".intercalate (theConfigs.map (fun cf => toString (cprsize cf.cfprog))))' \
    | timeout 2400 lake env lean --stdin) || { echo "gen: cannot compute the ring sizes" >&2; exit 1; }
  read -r -a R <<< "$rings"
  if [ "${#R[@]}" -ne "$NCONF" ]; then
    echo "gen: expected $NCONF ring sizes, got ${#R[@]}" >&2; exit 1
  fi
  mkdir -p "$DIR"
  local i r
  for i in $(seq 1 "$NCONF"); do
    r=${R[$((i - 1))]}
    cat > "$DIR/$(modname "$i").lean" <<EOF
/-
Copyright (c) 2026. Lean 4 port of the Coq/Rocq formal proof of the Four Color Theorem
by Georges Gonthier (math-comp/fourcolor).
Original Coq development: (c) 2006-2018 Microsoft Corporation and Inria, CeCILL-B.
-/
import FourColor.Reducibility.Nets$r
import FourColor.CfReducible

/-!
Generated by \`scripts/build_reducibility.sh gen\`: the C-reducibility certificate of
\`$(cfname "$i")\` (ring size $r), \`FourColor.$(cfname "$i")_reducible : CfReducible $(cfname "$i")\`.
-/

namespace FourColor

#engine_certify $(cfname "$i")

end FourColor
EOF
  done
  {
    cat <<'EOF'
/-
Copyright (c) 2026. Lean 4 port of the Coq/Rocq formal proof of the Four Color Theorem
by Georges Gonthier (math-comp/fourcolor).
Original Coq development: (c) 2006-2018 Microsoft Corporation and Inria, CeCILL-B.
-/
import FourColor.CfReducible
EOF
    for i in $(seq 1 "$NCONF"); do echo "import FourColor.Reducibility.$(modname "$i")"; done
    cat <<'EOF'

/-!
# C-reducibility of the 633 configurations (port of `reducibility.v`)

`theReducibility` (math-comp `the_reducibility : reducibility`, where `present.v` defines
`reducibility := reducible_in_range 0 (size the_configs) the_configs`): every configuration of
`theConfigs` is C-reducible.  It collates the certificates `cfNNN_reducible` of the generated
modules `FourColor/Reducibility/CfNNN.lean` (the replacement for the `job*`/`task*` files).

This file is generated by `scripts/build_reducibility.sh gen`.
-/

namespace FourColor

EOF
    # The certificates are collated in blocks of BLK configurations (reducible_in_range_cons),
    # and the blocks by cat_reducible_range, so that no proof term is nested more than about
    # BLK + NCONF / BLK deep (Palomar's checkers limit the nesting depth).
    local BLK=32 b lo hi nb
    nb=$(( (NCONF + BLK - 1) / BLK ))
    for b in $(seq 0 $((nb - 1))); do
      lo=$(( b * BLK )); hi=$(( lo + BLK )); [ "$hi" -gt "$NCONF" ] && hi=$NCONF
      # (`maxRecDepth`: the elaborator walks `theConfigs` recursively to unify the indices.)
      echo "set_option maxRecDepth 8000 in"
      echo "/-- The configurations of indices $lo … $((hi - 1)) are C-reducible. -/"
      echo "theorem reducibleBlock$b : ReducibleInRange $lo $hi theConfigs :="
      for i in $(seq $((lo + 1)) "$hi"); do
        echo "  reducible_in_range_cons $(cfname "$i")_reducible <|"
      done
      echo "  reducible_in_range_nil $hi theConfigs"
      echo
    done
    cat <<'EOF'
/-- math-comp `the_reducibility : reducibility`: all the configurations of `theConfigs` are
C-reducible. -/
theorem theReducibility : ReducibleInRange 0 633 theConfigs :=
EOF
    for b in $(seq 0 $((nb - 1))); do
      if [ "$b" -lt $((nb - 1)) ]; then
        echo "  cat_reducible_range reducibleBlock$b <|"
      else
        echo "  reducibleBlock$b"
      fi
    done
    cat <<'EOF'

end FourColor
EOF
  } > FourColor/Reducibility.lean
  echo "gen: wrote $NCONF files $DIR/CfNNN.lean and FourColor/Reducibility.lean"
}

# ---------------------------------------------------------------------------- build
build() {
  local J=3 A=1 B=$NCONF ONLY="" TMO=2400 LOG=.lake/reducibility/timings.tsv DIRECT=0 DRY=0 COLLATE=1
  while [ $# -gt 0 ]; do
    case "$1" in
      -j) J=$2; shift 2 ;;
      --range) A=$2; B=$3; shift 3 ;;
      --only) ONLY=$2; shift 2 ;;
      --timeout) TMO=$2; shift 2 ;;
      --log) LOG=$2; shift 2 ;;
      --direct) DIRECT=1; shift ;;
      --dry-run) DRY=1; shift ;;
      --no-collate) COLLATE=0; shift ;;
      *) echo "build: unknown option $1" >&2; exit 2 ;;
    esac
  done
  local nums
  if [ -n "$ONLY" ]; then nums=$(printf '%s\n' $ONLY | sort -n | uniq); else nums=$(seq "$A" "$B"); fi
  local n i f r
  local rings=()
  for i in $nums; do
    f=$DIR/$(modname "$i").lean
    [ -f "$f" ] || { echo "build: $f missing (run: $0 gen)" >&2; exit 1; }
    r=$(sed -n 's/^import FourColor\.Reducibility\.Nets\([0-9]*\)$/\1/p' "$f")
    rings+=("$r")
  done
  n=$(echo "$nums" | wc -w | tr -d ' ')
  local ringset
  ringset=$(printf '%s\n' "${rings[@]}" | sort -n | uniq | tr '\n' ' ')
  [ "$DRY" = 1 ] || mkdir -p "$(dirname "$LOG")/logs"
  [ "$DRY" = 1 ] || [ -f "$LOG" ] || printf 'cf\tring\trc\twall_s\tcpu_s\tmaxrss_MB\tanon_MB\tolean_bytes\n' > "$LOG"
  echo "build: $n configurations (ring sizes $ringset), $J at a time, log $LOG"

  # (1) prerequisites
  local pre="FourColor.CfReducible"
  for r in $ringset; do pre="$pre FourColor.Reducibility.Nets$r"; done
  if [ "$DIRECT" = 1 ]; then
    for m in $pre; do
      local o=.lake/build/lib/lean/${m//.//}.olean
      [ -f "$o" ] || { echo "build --direct: $o missing (build it first)" >&2; exit 1; }
    done
  elif [ "$DRY" = 1 ]; then
    echo "lake build $pre"
  else
    lake build $pre || { echo "build: prerequisites failed" >&2; exit 1; }
  fi

  # (2) the certificates, J at a time, in order
  export ROOT DIRECT DRY TMO LOG DIR
  local logdir
  logdir=$(dirname "$LOG")/logs
  export logdir
  one() {
    local i=$1 cf mod f r out rc olean cmd
    cf=$(printf 'cf%03d' "$i"); mod=$(printf 'Cf%03d' "$i")
    f=$DIR/$mod.lean
    r=$(sed -n 's/^import FourColor\.Reducibility\.Nets\([0-9]*\)$/\1/p' "$f")
    olean=.lake/build/lib/lean/FourColor/Reducibility/$mod.olean
    if [ "$DIRECT" = 1 ]; then
      cmd=(scripts/lean.sh -o "$olean" \
        -i .lake/build/lib/lean/FourColor/Reducibility/$mod.ilean "$f")
    else
      cmd=(lake build "FourColor.Reducibility.$mod")
    fi
    if [ "$DRY" = 1 ]; then echo "${cmd[*]}"; return 0; fi
    out=$(MEMTIME_TIMEOUT=$TMO memtime "$cf" "${cmd[@]}" \
      > "$logdir/$mod.log" 2>&1; tail -n 1 "$logdir/$mod.log")
    rc=$(sed -n 's/.* rc=\([^ ]*\).*/\1/p' <<< "$out")
    local wall cpu rss anon size
    wall=$(sed -n 's/.* wall=\([0-9.]*\)s.*/\1/p' <<< "$out")
    cpu=$(sed -n 's/.* cpu=\([0-9.]*\)s.*/\1/p' <<< "$out")
    rss=$(sed -n 's/.* maxrss=\([0-9.]*\)MB.*/\1/p' <<< "$out")
    anon=$(sed -n 's/.* anon=\([0-9.]*\)MB.*/\1/p' <<< "$out")
    size=$(wc -c < "$olean" 2>/dev/null | tr -d ' '); size=${size:-0}
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$cf" "$r" "$rc" "$wall" "$cpu" "$rss" "$anon" \
      "$size" >> "$LOG"
    if [ "$rc" = 0 ]; then
      echo "ok   $cf ring $r ${wall}s anon ${anon}MB olean ${size}B"
    else
      echo "FAIL $cf ring $r rc=$rc (log $logdir/$mod.log)"; return 1
    fi
  }
  export -f one memtime
  local failed=0
  echo "$nums" | xargs -P "$J" -n 1 bash -c 'one "$0"' || failed=1

  # (3) the collation
  if [ "$failed" = 1 ]; then echo "build: some certificates failed" >&2; exit 1; fi
  if [ "$n" = "$NCONF" ] && [ "$COLLATE" = 1 ]; then
    if [ "$DIRECT" = 1 ]; then
      cmd="scripts/lean.sh -o .lake/build/lib/lean/FourColor/Reducibility.olean -i .lake/build/lib/lean/FourColor/Reducibility.ilean FourColor/Reducibility.lean"
    else
      cmd="lake build FourColor.Reducibility"
    fi
    if [ "$DRY" = 1 ]; then echo "$cmd"
    else
      MEMTIME_TIMEOUT=$TMO memtime Reducibility $cmd || exit 1
    fi
  fi
  if [ "$DRY" = 0 ]; then
    awk -F'\t' 'NR > 1 && $3 == "0" { w[$2] += $4; c[$2]++; if ($7 > m[$2]) m[$2] = $7; s[$2] += $8 }
      END { for (r in w) printf "ring %s: %d modules, %.0f s wall, max anon %.0f MB, %.1f MB olean\n",
            r, c[r], w[r], m[r], s[r] / 1e6 }' "$LOG" | sort -t' ' -k2 -n
  fi
}

case "${1:-}" in
  gen) shift; gen "$@" ;;
  build) shift; build "$@" ;;
  *) sed -n '2,36p' "$0"; exit 2 ;;
esac
